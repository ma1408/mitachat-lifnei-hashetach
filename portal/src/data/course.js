export const TOTAL_LESSONS = lessonOrder.length

export function getModuleById(moduleId) {
  return modules.find((m) => m.id === moduleId)
}

export function getLessonById(lessonId) {
  return lessons[lessonId] || null
}

export function getNextLessonId(lessonId) {
  const idx = lessonOrder.indexOf(lessonId)
  if (idx === -1 || idx === lessonOrder.length - 1) return null
  return lessonOrder[idx + 1]
}

export function getPrevLessonId(lessonId) {
  const idx = lessonOrder.indexOf(lessonId)
  if (idx <= 0) return null
  return lessonOrder[idx - 1]
}
